// Builds the deployable site into _site/ (only public files) and generates the
// Cloudflare Pages _headers file with a Content-Security-Policy whose script
// hashes match the inline <script> blocks of index.html.
import { createHash } from 'node:crypto';
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const out = join(root, '_site');

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

cpSync(join(root, 'index.html'), join(out, 'index.html'));
cpSync(join(root, 'public'), out, { recursive: true });

function inlineScriptHashes(html) {
  const hashes = [];
  for (const [, body] of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)) {
    hashes.push(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
  return hashes;
}

const scriptHashes = inlineScriptHashes(readFileSync(join(out, 'index.html'), 'utf8'));
if (scriptHashes.length === 0) throw new Error('No inline scripts found in index.html');

const csp = [
  "default-src 'none'",
  `script-src ${scriptHashes.join(' ')}`,
  // index.html uses an inline <style> block and a few style="" attributes.
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "img-src 'self' data:",
  "connect-src 'self'",
  "manifest-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
].join('; ');

const headers = `# Generated by scripts/build.mjs. Do not edit in _site/.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin

/fonts/*
  Cache-Control: public, max-age=31536000, immutable

/favicon.svg
  Cache-Control: public, max-age=86400

/logo.svg
  Cache-Control: public, max-age=86400

/og-image.png
  Cache-Control: public, max-age=86400
`;

writeFileSync(join(out, '_headers'), headers);

console.log(`Built _site/ with ${scriptHashes.length} inline script hash(es).`);
